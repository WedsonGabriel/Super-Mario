# ====================================================================
# GERENCIADOR DE ESTADOS DE RENDERIZAÇÃO DO PLAYER (MÁRIO)
# ====================================================================
draw_player:
	lw $8, mario_direction
	lw $9, mario_is_moving
	
	beq $9, 0, draw_idle
	
draw_walk:
	beq $8, 1, load_walk_right
	j load_walk_left

draw_idle:
	beq $8, 1, load_idle_right
	j load_idle_left

# --- Seletores de Endereço de Memória de Sprite ---
load_walk_right:
	la $4, mario_andando_direita
	j render_mario_sprite

load_walk_left:
	la $4, mario_andando_esquerda
	j render_mario_sprite

load_idle_right:
	la $4, mario_parado_direita
	j render_mario_sprite

load_idle_left:
	la $4, mario_parado_esquerda
	j render_mario_sprite

# ====================================================================
# MOTOR DE RENDERIZAÇÃO GRÁFICA DO MARIO
# ====================================================================
render_mario_sprite:
	add $24, $0, $4         # $24 = Ponteiro de leitura da matriz de dados do Mario
	lw $9, pos_player_line 
	lw $10, pos_player_column 
	lui $11, 0x1001 
	lw $12, height_mario 

	# CALCULAR ENDEREÇO INICIAL DE ESCRITA NA TELA
	sll $9, $9, 7          
	add $10, $10, $9       
	sll $10, $10, 2        
	add $10, $10, $11      
	
	line_mario:	
		beq $12, $0, end_draw_mario
		lw $13, width_mario 

	column_mario:	
		beq $13, $0, end_column_mario
		lw $14, 0($24)      # obtém a cor do pixel do mario
		
		beq $14, 0x0000ff00, skip_pixel_mario # ignora cor verde
		
		# colisão
		lw $15, 0($10) # lê o pixel que já está impresso na tela
		beq $15, 0x00ffffff, hit # identifica o ponto de impacto com o branco (fantasma ou bráulio)
		
		sw $14, 0($10)      # Se livre de colisão, plota o pixel na tela normalmente
		j skip_pixel_mario

	hit:
		lw $15, current_phase
		beq $15, 0, trigger_game_over # se a fase for 0 (Inferno), vai para o game over
		
		# se for qualquer valor diferente de 0 (fase 1), vai para a vitória (bráulio)
		j trigger_victory

	trigger_game_over:
		addi $15, $0, 1
		sw $15, game_state # altera o estado para 1 (game over)
		sw $14, 0($10)               
		j skip_pixel_mario

	trigger_victory:
		addi $15, $0, 4 # altera o estado do jogo para 4 (you win)
		sw $15, game_state
		sw $14, 0($10) # renderiza o pixel de sobreposição do Mario
		j skip_pixel_mario

	skip_pixel_mario:
		add $24, $24, 4 # avança ponteiro do sprite
		add $10, $10, 4 # avança ponteiro da VRAM
		sub $13, $13, 1     
		j column_mario
			
	end_column_mario:
		addi $10, $10, 452  # salto de linha da tela proporcional à largura (512 - 60)
		sub $12, $12, 1     
		j line_mario 

end_draw_mario:
	jr $31