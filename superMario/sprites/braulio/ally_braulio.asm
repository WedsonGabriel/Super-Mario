# entrada: $4 (endereço de memória do frame atual do braulio)
# alterados: $8 a $14, $24
# saída: void
draw_braulio:
	add $24, $0, $4 # $24 = ponteiro de leitura
	lw $9, pos_braulio_line # carrega LINHA (Y) em $9
	lw $10, pos_braulio_column # carrega COLUNA (X) em $10
	lui $11, 0x1001 # base da tela
	lw $12, height_braulio # carrega a altura em $12 

	# CALCULAR POSIÇÃO INICIAL DA TELA
	sll $9, $9, 7 # $9 = Y * 128
	add $10, $10, $9 # $10 = X + (Y * 128)
	sll $10, $10, 2 # multiplica por 4
	add $10, $10, $11 # Base + Offset
	
	# LOOP EXTERNO (Linhas)
	line_braulio:	
		beq $12, $0, end_draw_braulio
		lw $13, width_braulio

	# LOOP INTERNO (Colunas)
	column_braulio:	
		beq $13, $0, end_column_braulio
		
		lw $14, 0($24) # pega a cor do pixel
		beq $14, 0x0000FF00, drop_column_braulio # se for VERDE, ignora
		
		sw $14, 0($10) # pinta o pixel na tela

		drop_column_braulio:
			add $24, $24, 4 
			add $10, $10, 4 
			sub $13, $13, 1 
			j column_braulio
			
	end_column_braulio:
		addi $10, $10, 472 # (512 - 40 bytes andados = 472)
		sub $12, $12, 1 
		j line_braulio 

end_draw_braulio:
	jr $31

