earth:
	add $25, $0, $31 
	
	la $15, frames_braulio # carrega o endereço dos frames   
	lw $16, current_braulio_frame # carrega o frame atual
	add $15, $15, $16          
	
	lw $4, 0($15)              
	beq $4, $0, reset_breathe_frame  
	j draw_braulio_frame

reset_breathe_frame:
	sw $0, current_braulio_frame   
	la $15, frames_braulio
	lw $4, 0($15)
	
draw_braulio_frame:
	jal draw_braulio           
	
	lw $16, current_braulio_frame
	addi $16, $16, 4
	sw $16, current_braulio_frame
	
	jr $25